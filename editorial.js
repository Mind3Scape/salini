(function (global) {
  'use strict';
  let data = null;
  let loading = null;
  const scriptURL = typeof document !== 'undefined' && document.currentScript ? document.currentScript.src : null;
  const esc = value => String(value == null ? '' : value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const pathOf = value => ('/' + String(value || '').replace(/^#?\/?/, '')).split('?')[0].replace(/\/$/, '') || '/';
  const groups = ['collections', 'articles', 'projects', 'pages'];
  const records = () => data ? groups.flatMap(k => data[k] || []) : [];
  const allRecords = () => [...records(), ...(data?.academy || [])];
  const norm = value => String(value || '').toLocaleLowerCase('ru').replace(/ё/g, 'е');
  const link = path => '#' + path;
  const date = value => {
    if (!value) return '';
    const v = String(value).slice(0, 10);
    return /^\d{4}-\d{2}-\d{2}$/.test(v) ? v.split('-').reverse().join('.') : value;
  };
  function load() {
    if (data) return Promise.resolve(data);
    if (!loading) {
      const base = scriptURL || (typeof location !== 'undefined' ? location.href : 'http://localhost/');
      loading = fetch(new URL('editorial.json', base), {cache:'no-cache'}).then(r => {
        if (!r.ok) throw new Error('Не удалось загрузить материалы Salini');
        return r.json();
      }).then(value => { data = value; return data; }).catch(error => { loading = null; throw error; });
    }
    return loading;
  }
  function handles(path) {
    return /^\/(collections|collection(?:\/[^/]+)?|journal(?:\/[^/]+)?|projects(?:\/[^/]+)?|academy|about|cooperation|new)$/.test(pathOf(path));
  }
  function sourceNote(record) {
    const p = record.provenance || {};
    const label = p.status === 'current' ? `Оригинал проверен ${date(p.sourceDate)}` : `Архив · ${date(p.sourceDate || data?.archiveDate)}`;
    return `<aside class="ed-source"><span class="ed-source-label${p.status === 'current' ? '' : ' is-archive'}">${esc(label)}</span><a href="${esc(record.sourceUrl)}" target="_blank" rel="noopener noreferrer">Первоисточник ↗</a>${p.status === 'archive' ? '<p>Сохранённая публикация Salini. Условия, ассортимент и ссылки в ней могут быть неактуальны.</p>' : record.kind === 'articles' ? '<p>Материал отражает информацию на дату публикации. Текущие условия уточняйте у Salini.</p>' : ''}</aside>`;
  }
  function photo(image, title, options = {}) {
    if (!image?.src) return '';
    return `<img src="${esc(image.src)}" width="${Number(image.width) || 1400}" height="${Number(image.height) || 900}" alt="${esc(image.alt || title)}" loading="${options.eager ? 'eager' : 'lazy'}" decoding="async"${options.eager ? ' fetchpriority="high"' : ''}>`;
  }
  function breadcrumb(label, href) {
    return `<nav class="ed-breadcrumb" aria-label="Хлебные крошки"><a href="#/">Главная</a><span aria-hidden="true">/</span>${href ? `<a href="${esc(link(href))}">${esc(label)}</a>` : `<span>${esc(label)}</span>`}</nav>`;
  }
  function routeURL(url, products) {
    if (!url) return '#';
    if (/^(mailto:|tel:)/i.test(url)) return url;
    let u;
    try { u = new URL(url, 'https://salini-srl.com'); } catch (_) { return '#'; }
    if (!['https:', 'http:'].includes(u.protocol)) return '#';
    if (/^(www\.)?salini-srl\.com$/.test(u.hostname)) {
      if (u.hash) return u.href;
      const sourcePath = u.pathname.replace(/\/$/, '');
      const known = records().find(r => new URL(r.sourceUrl).pathname.replace(/\/$/, '') === sourcePath);
      if (known) return link(known.path);
      const product = products.find(p => { try { return new URL(p.sourceUrl).pathname.replace(/\/$/, '') === sourcePath; } catch (_) { return false; } });
      if (product) return '#/product/' + encodeURIComponent(product.id);
      const routes = {'/blog':'/journal','/gallery':'/projects','/e_learning':'/academy','/about-company':'/about','/cooperation':'/cooperation','/new':'/new','/contacts':'/contacts','/where-buy':'/dealers','/service':'/service','/faq':'/help','/dostavka-i-oplata':'/delivery'};
      if (routes[sourcePath]) return link(routes[sourcePath]);
    }
    return u.href;
  }
  function richHTML(html, products) {
    // HTML is generated by the importer from a strict inline tag allowlist.
    return String(html || '').replace(/href="([^"]+)"/g, (_, href) => {
      const decoded = href.replace(/&amp;/g, '&').replace(/&#x27;/g, "'").replace(/&quot;/g, '"');
      const destination = routeURL(decoded, products);
      return `href="${esc(destination)}"${destination.startsWith('http') ? ' target="_blank" rel="noopener noreferrer"' : ''}`;
    });
  }
  function renderBlocks(record, products) {
    products = [...products, ...(record.relatedProducts || []).filter(p => !products.some(x => x.id === p.id))];
    const hero = record.images?.[0]?.src;
    let skippedHero = false;
    return (record.blocks || []).map(block => {
      if (block.type === 'image') {
        if (!skippedHero && block.image?.src === hero) { skippedHero = true; return ''; }
        return `<figure class="ed-figure">${photo(block.image, record.title)}</figure>`;
      }
      if (block.type === 'video') return `<a class="ed-video-link" href="${esc(block.url)}" target="_blank" rel="noopener noreferrer"><span aria-hidden="true">▷</span>${esc(block.title || 'Видео Salini')}<span aria-hidden="true">↗</span></a>`;
      if (block.type === 'heading') return `<h2>${richHTML(block.html || esc(block.text), products)}</h2>`;
      if (block.type === 'quote') return `<blockquote>${richHTML(block.html || esc(block.text), products)}</blockquote>`;
      return `<p>${richHTML(block.html || esc(block.text), products)}</p>`;
    }).join('');
  }
  function productSection(record, products) {
    const associated = (record.productIds || []).map(id => products.find(p => p.id === id) || (record.relatedProducts || []).find(p => p.id === id)).filter(Boolean);
    if (!associated.length) return '';
    return `<section class="ed-related"><div class="ed-section-head"><span class="eyebrow">Изделия в материале</span><h2>Продолжение истории</h2><p>Связи с изделиями сохранены по ссылкам оригинальной публикации.</p></div><div class="ed-product-grid">${associated.map(p => `<a class="ed-product-card" href="#/product/${encodeURIComponent(p.id)}">${photo(p.image, p.name)}<span>${esc(p.subtitle || p.category)}</span><h3>${esc(p.name)}</h3><p>${esc(p.dimensionsLabel)}</p></a>`).join('')}</div></section>`;
  }
  function detail(record, products) {
    const back = record.kind === 'collections' ? ['Коллекции', '/collections'] : record.kind === 'articles' ? ['Журнал', '/journal'] : record.kind === 'projects' ? ['Проекты', '/projects'] : [record.title, null];
    const subtitle = record.kind === 'collections' ? 'Коллекция Salini' : record.category || (record.kind === 'projects' ? 'Галерея проектов' : 'Мир Salini');
    const relatedCTA = record.path === '/cooperation' ? `<section class="ed-contact"><span class="eyebrow">Начать разговор</span><h2>Создадим пространство вместе</h2><p>Дизайнерам и архитекторам — профессиональная поддержка. Партнёрам — условия сотрудничества напрямую от Salini.</p><div><a class="ed-action" href="mailto:design@salini-srl.com">Написать о проекте ↗</a><a class="ed-action ed-action-light" href="mailto:info@salini-srl.com">Стать партнёром ↗</a></div></section>` : '';
    return `<article class="ed-page ed-detail wrap" data-editorial-route="${esc(record.path)}">${breadcrumb(...back)}<header class="ed-detail-head"><span class="eyebrow">${esc(subtitle)}</span><h1>${esc(record.title)}</h1>${record.publishedAt || record.author ? `<p class="ed-byline">${[record.publishedAt && date(record.publishedAt), record.author].filter(Boolean).map(esc).join(' · ')}</p>` : ''}${record.authors?.length ? `<p class="ed-byline">Дизайнер: ${record.authors.map(esc).join(', ')}</p>` : ''}</header>${record.images?.length ? `<figure class="ed-cover">${photo(record.images[0], record.title, {eager:true})}</figure>` : ''}<div class="ed-reading-layout">${sourceNote(record)}<div class="ed-prose">${renderBlocks(record, products)}</div></div>${productSection(record, products)}${relatedCTA}<a class="ed-back" href="${esc(link(back[1] || '/'))}">← ${back[1] ? 'Ко всем материалам' : 'На главную'}</a></article>`;
  }
  const indexConfig = {
    '/collections': {key:'collections', label:'Коллекции', eyebrow:'Форма. Характер. Пространство.', title:'Одна философия.<br><em>Разные истории.</em>', text:'Авторские коллекции Salini: от первого замысла до предметов, с которыми начинается интерьер.'},
    '/journal': {key:'articles',label:'Журнал',eyebrow:'Мир Salini',title:'Вдохновение<br><em>в деталях.</em>',text:'Истории бренда, проекты, материалы и новости. Дата публикации и версия первоисточника сохранены в каждом материале.'},
    '/projects': {key:'projects',label:'Проекты',eyebrow:'Галерея интерьеров',title:'Место для<br><em>своего ритма.</em>',text:'51 интерьерная история Salini из архива 6 октября 2026 года. Оригинальный раздел галереи сейчас недоступен.'},
    '/academy': {key:'academy',label:'Академия',eyebrow:'Знания, которыми делимся',title:'Узнать материал.<br><em>Понять форму.</em>',text:'Видео Salini о коллекциях, технологиях, уходе и работе с изделиями. Смотрите на официальном канале Rutube.'}
  };
  function card(record, academy=false) {
    const image = academy ? record.image : record.images?.[0];
    const href = academy ? record.videoUrl : link(record.path);
    const target = academy ? ' target="_blank" rel="noopener noreferrer"' : '';
    return `<a class="ed-card${academy ? ' ed-card-video' : ''}" href="${esc(href)}"${target}>${image ? `<div class="ed-card-image">${photo(image, record.title)}${academy ? '<span class="ed-play" aria-hidden="true">▷</span>' : '<span class="ed-card-arrow" aria-hidden="true">↗</span>'}</div>` : '<div class="ed-card-image ed-card-plain"><span>SALINI</span></div>'}<div class="ed-card-meta"><span>${esc(record.category || (record.kind === 'collections' ? 'Коллекция' : 'Salini'))}</span>${record.publishedAt ? `<time>${esc(date(record.publishedAt))}</time>` : ''}</div><h2>${esc(record.title)}</h2>${record.description ? `<p>${esc(record.description.slice(0, 175))}${record.description.length > 175 ? '…' : ''}</p>` : ''}<span class="ed-card-status">${academy ? 'Смотреть на Rutube ↗' : record.provenance?.status === 'archive' ? 'Архив · ' + date(record.provenance.sourceDate) : 'Читать историю'}</span></a>`;
  }
  function paramsValue(params, key) {
    return params?.get ? params.get(key) || '' : params?.[key] || '';
  }
  function filtered(items, q, category) {
    const needle = norm(q);
    return items.filter(r => (!category || r.category === category) && (!needle || norm([r.title,r.description,r.category,...(r.blocks || []).map(b => b.text || '')].join(' ')).includes(needle)));
  }
  function index(path, params) {
    const conf = indexConfig[path];
    const items = data[conf.key] || [];
    const q = paramsValue(params, 'q');
    const category = paramsValue(params, 'category');
    const categories = [...new Set(items.map(r => r.category).filter(Boolean))].sort((a,b) => a.localeCompare(b,'ru'));
    const visible = filtered(items,q,category);
    return `<section class="ed-page ed-index wrap" data-editorial-route="${esc(path)}">${breadcrumb(conf.label)}<header class="ed-index-head"><div><span class="eyebrow">${esc(conf.eyebrow)}</span><h1>${conf.title}</h1></div><p>${esc(conf.text)}</p></header><form class="ed-filters" role="search"><label class="ed-search"><span class="sr-only">Поиск по разделу ${esc(conf.label)}</span><input type="search" name="q" placeholder="Найти историю, коллекцию, тему…" value="${esc(q)}" autocomplete="off"><span aria-hidden="true">⌕</span></label>${categories.length > 1 ? `<label class="ed-category"><span class="sr-only">Категория</span><select name="category"><option value="">Все темы</option>${categories.map(c => `<option value="${esc(c)}"${c===category?' selected':''}>${esc(c)}</option>`).join('')}</select></label>` : ''}<p class="ed-result-count" aria-live="polite">${visible.length} из ${items.length}</p></form><div class="ed-card-grid" data-editorial-results>${visible.map(r => card(r, path==='/academy')).join('')}</div><p class="ed-empty"${visible.length ? ' hidden' : ''}>Ничего не найдено. Попробуйте другую тему или сократите запрос.</p></section>`;
  }
  function render(path, params, options = {}) {
    if (!data) return '<section class="ed-page wrap"><p>Материалы загружаются…</p></section>';
    const normalized = pathOf(path);
    if (indexConfig[normalized]) return index(normalized,params);
    const record = records().find(r => r.path === normalized);
    if (record) return detail(record,options.products || []);
    return `<section class="ed-page wrap"><h1>Материал не найден</h1><p>Посмотрите другие истории Salini.</p><a class="ed-action" href="#/journal">Открыть журнал</a></section>`;
  }
  function mount(main, path, params, options = {}) {
    const normalized = pathOf(path);
    if (!data || !indexConfig[normalized]) return;
    const form = main.querySelector('.ed-filters');
    if (!form) return;
    const update = () => {
      const q = form.elements.q?.value || '';
      const category = form.elements.category?.value || '';
      const items = data[indexConfig[normalized].key] || [];
      const visible = filtered(items,q,category);
      main.querySelector('[data-editorial-results]').innerHTML = visible.map(r => card(r,normalized==='/academy')).join('');
      main.querySelector('.ed-result-count').textContent = `${visible.length} из ${items.length}`;
      main.querySelector('.ed-empty').hidden = !!visible.length;
    };
    form.addEventListener('submit', event => { event.preventDefault(); update(); });
    form.addEventListener('input', update);
    form.addEventListener('change', update);
  }
  function getPages() {
    if (!data) return [];
    const indexes = Object.entries(indexConfig).map(([path,c]) => ({path,title:c.label + ' — Salini',description:c.text,html:render(path)}));
    return [...indexes,...records().map(r => ({path:r.path,title:r.title + ' — Salini',description:r.description.slice(0,240),html:render(r.path)}))];
  }
  function search(q) {
    if (!data || !cleanQuery(q)) return [];
    return filtered(allRecords(),q,'').slice(0,60).map(r => ({title:r.title,href:r.videoUrl || link(r.path),excerpt:(r.description || r.category || '').slice(0,160)}));
  }
  function cleanQuery(q) { return String(q || '').trim(); }
  global.SaliniEditorial = {load,handles,render,mount,getPages,search};
})(typeof window !== 'undefined' ? window : globalThis);
